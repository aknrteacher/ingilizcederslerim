function extractVocab(filePath) {
  const full = path.join(clientRoot, filePath);
  const t = fs.readFileSync(full, "utf8");
  const m = t.match(/const allVocabulary = \[([\s\S]*?)\];/);
  if (!m) throw new Error("no allVocabulary in " + filePath);
  const rows = [];
  const re = /\{\s*word:\s*"([^"]+)"\s*,\s*file:\s*"([^"]+)"/g;
  let x;
  while ((x = re.exec(m[1]))) {
    const word = x[1];
    const file = x[2];
    const speakWord = word.toLowerCase();
    rows.push({ word, speakWord, file });
  }
  return rows;
}

